export function translateUiMessage(text: string, language: "en" | "zh"): string {
  if (language !== "zh") return text;
  if (text.includes("\n")) {
    const parts = text.split("\n");
    const allKnown = parts.every(part => Object.hasOwn(uiMessagesZh, part) || dynamicMessagesZh.some(([pattern]) => pattern.test(part)));
    return allKnown ? parts.map(part => translateUiMessage(part, language)).join("\n") : text;
  }
  if (Object.hasOwn(uiMessagesZh, text)) return uiMessagesZh[text];
  for (const [pattern, format] of dynamicMessagesZh) {
    const match = text.match(pattern);
    if (match) return format(...match);
  }
  return text;
}
